#!/usr/bin/env bash
# ============================================
# apply-theme.sh — Distribute colors.json to all consumers
# ============================================
# Reads ~/.config/theme/colors.json and generates themed configs for:
#   Hyprland, Kitty, Neovim, Starship, Hyprlock, Zathura
#
# Usage: apply-theme.sh [--no-reload]

set -euo pipefail

THEME_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/theme"
CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}"
COLORS_FILE="$THEME_DIR/colors.json"

[[ -f "$COLORS_FILE" ]] || { echo "Missing $COLORS_FILE" >&2; exit 1; }
command -v jq &>/dev/null || { echo "jq is required" >&2; exit 1; }

NO_RELOAD=false
KITTY_ONLY=false
for arg in "$@"; do
    case "$arg" in
        --no-reload)  NO_RELOAD=true ;;
        --kitty-only) KITTY_ONLY=true ;;
    esac
done

# ── Helpers ────────────────────────────────────────────────

# Read color as hex without # (e.g., "cba6f7")
c() { jq -r ".[\"$1\"] // empty" "$COLORS_FILE" | tr -d '#' | tr '[:upper:]' '[:lower:]'; }

# Read color with # prefix (e.g., "#cba6f7")
ch() { jq -r ".[\"$1\"] // empty" "$COLORS_FILE"; }

# Read color uppercase without # (e.g., "CBA6F7")
cu() { jq -r ".[\"$1\"] // empty" "$COLORS_FILE" | tr -d '#' | tr '[:lower:]' '[:upper:]'; }

# ── Catppuccin palette generation (shared by nvim + starship) ────
#
# catppuccin26.py takes a seed color and hue-rotates the entire Catppuccin
# Mocha palette in CIELAB LCH space — same perceptually uniform approach
# as dank16.py for ANSI terminal colors.  Every accent gets its own
# distinct hue; surfaces get a subtle tint from the seed.

PALETTE_KEYS=(rosewater flamingo pink mauve red maroon peach yellow green teal sky sapphire blue lavender text subtext1 subtext0 overlay2 overlay1 overlay0 surface2 surface1 surface0 base mantle crust)

# Generate palette JSON from source_color (or default to Catppuccin Mocha)
_palette_json=""
_generate_palette() {
    local source_color
    source_color=$(jq -r '.source_color // empty' "$COLORS_FILE")
    if [[ -n "$source_color" ]]; then
        _palette_json=$(python3 "$THEME_DIR/catppuccin26.py" "$source_color")
    else
        # Static mode — identity (original Catppuccin Mocha)
        _palette_json=$(python3 "$THEME_DIR/catppuccin26.py")
    fi
}

# Read a generated palette color
pc() { echo "$_palette_json" | jq -r ".[\"$1\"] // empty"; }

# Emit palette lines in lua or toml format
palette_lines() {
    local fmt="${1:-toml}"
    for key in "${PALETTE_KEYS[@]}"; do
        local value
        value="$(pc "$key")"
        case "$fmt" in
            lua)  printf '  %-9s = "%s",\n' "$key" "$value" ;;
            toml) printf '%s = "%s"\n' "$key" "$value" ;;
        esac
    done
}

# Convert hex to rgba(r,g,b,a) for zathura
hex_to_rgba() {
    local hex
    hex="$(echo "$1" | tr -d '#')"
    local r=$((16#${hex:0:2}))
    local g=$((16#${hex:2:2}))
    local b=$((16#${hex:4:2}))
    echo "rgba($r,$g,$b,${2:-1})"
}

# ── Hyprland generated.conf ───────────────────────────────

generate_hyprland() {
    local out="$CONFIG_DIR/hypr/themes/generated.conf"
    mkdir -p "$(dirname "$out")"

    cat > "$out" << EOF
# Auto-generated by apply-theme.sh — DO NOT EDIT
# Material You color variables for Hyprland

\$primary = rgb($(c primary))
\$primaryAlpha = $(c primary)
\$onPrimary = rgb($(c on_primary))
\$onPrimaryAlpha = $(c on_primary)

\$secondary = rgb($(c secondary))
\$secondaryAlpha = $(c secondary)
\$onSecondary = rgb($(c on_secondary))

\$tertiary = rgb($(c tertiary))
\$tertiaryAlpha = $(c tertiary)

\$error = rgb($(c error))
\$errorAlpha = $(c error)

\$surface = rgb($(c surface))
\$surfaceAlpha = $(c surface)
\$onSurface = rgb($(c on_surface))
\$onSurfaceAlpha = $(c on_surface)
\$onSurfaceVariant = rgb($(c on_surface_variant))
\$surfaceDim = rgb($(c surface_dim))
\$surfaceDimAlpha = $(c surface_dim)

\$surfaceContainer = rgb($(c surface_container))
\$surfaceContainerAlpha = $(c surface_container)
\$surfaceContainerHigh = rgb($(c surface_container_high))
\$surfaceContainerHighAlpha = $(c surface_container_high)
\$surfaceContainerHighest = rgb($(c surface_container_highest))
\$surfaceContainerLowest = rgb($(c surface_container_lowest))
\$surfaceContainerLowestAlpha = $(c surface_container_lowest)

\$outline = rgb($(c outline))
\$outlineVariant = rgb($(c outline_variant))

\$inverseSurface = rgb($(c inverse_surface))
\$inversePrimary = rgb($(c inverse_primary))

\$success = rgb($(c success))
\$warning = rgb($(c warning))
\$caution = rgb($(c caution))

# Pre-computed rgba for shadow (Hyprland can't interpolate vars in strings)
\$shadowColor = rgba($(c surface_container_lowest)aa)
\$shadowColorInactive = rgba($(c surface)aa)
EOF

    if [[ "$NO_RELOAD" == false ]]; then
        hyprctl reload &>/dev/null || true
    fi
}

# ── Kitty current-theme.conf ──────────────────────────────

generate_kitty() {
    local out="$CONFIG_DIR/kitty/current-theme.conf"
    mkdir -p "$(dirname "$out")"

    # Determine ANSI terminal colors (indices 0–15)
    # Dynamic mode: derive vibrant 16-color palette from wallpaper seed via dank16.py
    # Static mode:  use exact hardcoded Catppuccin Mocha ANSI values
    local SOURCE_COLOR
    SOURCE_COLOR=$(jq -r '.source_color // empty' "$COLORS_FILE")

    local -a ANSI_COLORS
    if [[ -n "$SOURCE_COLOR" ]]; then
        mapfile -t ANSI_COLORS < <(
            python3 "$THEME_DIR/dank16.py" "$SOURCE_COLOR" \
                | jq -r '.ansi[] | ltrimstr("#") | ascii_upcase'
        )
    else
        # Catppuccin Mocha exact ANSI values (order: 0–7, then 8–15)
        ANSI_COLORS=(
            "45475A" "F38BA8" "A6E3A1" "F9E2AF" "89B4FA" "CBA6F7" "94E2D5" "BAC2DE"
            "585B70" "F38BA8" "A6E3A1" "F9E2AF" "89B4FA" "CBA6F7" "94E2D5" "CDD6F4"
        )
    fi

    cat > "$out" << EOF
# vim:ft=kitty
# Auto-generated by apply-theme.sh — DO NOT EDIT

# The basic colors
foreground              #$(cu on_surface)
background              #$(cu surface)
selection_foreground    #$(cu surface)
selection_background    #$(cu primary)

# Cursor colors
cursor                  #$(cu primary)
cursor_text_color       #$(cu surface)

# URL underline color when hovering with mouse
url_color               #$(cu primary)

# Kitty window border colors
active_border_color     #$(cu secondary)
inactive_border_color   #$(cu outline)
bell_border_color       #$(cu warning)

# OS Window titlebar colors
wayland_titlebar_color system
macos_titlebar_color system

# Tab bar colors
active_tab_foreground   #$(cu on_primary)
active_tab_background   #$(cu primary)
inactive_tab_foreground #$(cu on_surface)
inactive_tab_background #$(cu surface_dim)
tab_bar_background      #$(cu surface_container_lowest)

# Colors for marks (marked text in the terminal)
mark1_foreground #$(cu surface)
mark1_background #$(cu secondary)
mark2_foreground #$(cu surface)
mark2_background #$(cu primary)
mark3_foreground #$(cu surface)
mark3_background #$(cu tertiary)

# The 16 terminal colors

# black
color0  #${ANSI_COLORS[0]}
color8  #${ANSI_COLORS[8]}

# red
color1  #${ANSI_COLORS[1]}
color9  #${ANSI_COLORS[9]}

# green
color2  #${ANSI_COLORS[2]}
color10 #${ANSI_COLORS[10]}

# yellow
color3  #${ANSI_COLORS[3]}
color11 #${ANSI_COLORS[11]}

# blue
color4  #${ANSI_COLORS[4]}
color12 #${ANSI_COLORS[12]}

# magenta
color5  #${ANSI_COLORS[5]}
color13 #${ANSI_COLORS[13]}

# cyan
color6  #${ANSI_COLORS[6]}
color14 #${ANSI_COLORS[14]}

# white
color7  #${ANSI_COLORS[7]}
color15 #${ANSI_COLORS[15]}
EOF

    if [[ "$NO_RELOAD" == false ]]; then
        # Send SIGUSR1 to kitty for live reload
        pkill -USR1 kitty &>/dev/null || true
    fi
}

# ── Neovim palette ────────────────────────────────────────

generate_nvim() {
    local out="$THEME_DIR/nvim-palette.lua"

    {
        echo '-- Auto-generated by apply-theme.sh — DO NOT EDIT'
        echo '-- Maps Material You colors back to Catppuccin names for catppuccin/nvim'
        echo 'return {'
        palette_lines lua
        echo '}'
    } > "$out"

    if [[ "$NO_RELOAD" == false ]]; then
        # Send SIGUSR1 to Neovim instances for live reload
        pkill -USR1 nvim &>/dev/null || true
    fi
}

# ── Starship palette ──────────────────────────────────────

generate_starship() {
    local conf="$CONFIG_DIR/starship.toml"
    [[ -f "$conf" ]] || return 0

    # Replace the [palettes.catppuccin_mocha] section in-place
    local tmp
    tmp="$(mktemp)"

    # Write everything up to and including [palettes.catppuccin_mocha]
    awk 'BEGIN{f=0} /^\[palettes\.catppuccin_mocha\]/{print;f=1;next} f&&/^\[/{f=0} f==0{print}' "$conf" > "$tmp"

    # Append the new palette values
    palette_lines toml >> "$tmp"

    cat "$tmp" > "$conf"
    rm -f "$tmp"
}

