@define-color headerbar_bg_color $(ch surface);
@define-color headerbar_fg_color $(ch on_surface);
@define-color card_bg_color $(ch surface_container);
@define-color card_fg_color $(ch on_surface);
@define-color popover_bg_color $(ch surface_container);
@define-color popover_fg_color $(ch on_surface);
@define-color sidebar_bg_color $(ch surface_dim);
@define-color sidebar_fg_color $(ch on_surface);
