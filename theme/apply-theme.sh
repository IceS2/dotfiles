EOF
}

# ── Zathura colors ────────────────────────────────────────

generate_zathura() {
    local out="$CONFIG_DIR/zathura/catppuccin-mocha"
    mkdir -p "$(dirname "$out")"

    local on_surface on_surface_variant surface surface_container
    local surface_dim surface_container_lowest primary error warning outline
    on_surface="$(ch on_surface)"
    on_surface_variant="$(ch on_surface_variant)"
    surface="$(ch surface)"
    surface_container="$(ch surface_container)"
    surface_dim="$(ch surface_dim)"
    surface_container_lowest="$(ch surface_container_lowest)"
    primary="$(ch primary)"
    error="$(ch error)"
    warning="$(ch warning)"
    outline="$(ch outline)"

    cat > "$out" << EOF
set default-fg                $(hex_to_rgba "$on_surface")
set default-bg                $(hex_to_rgba "$surface")

set completion-bg             $(hex_to_rgba "$surface_container")
set completion-fg             $(hex_to_rgba "$on_surface")
set completion-highlight-bg   $(hex_to_rgba "$primary")
set completion-highlight-fg   $(hex_to_rgba "$surface")
set completion-group-bg       $(hex_to_rgba "$surface_dim")
set completion-group-fg       $(hex_to_rgba "$on_surface")

set statusbar-fg              $(hex_to_rgba "$on_surface")
set statusbar-bg              $(hex_to_rgba "$surface_container_lowest")
set inputbar-fg               $(hex_to_rgba "$on_surface")
set inputbar-bg               $(hex_to_rgba "$surface")

set notification-bg           $(hex_to_rgba "$surface")
set notification-fg           $(hex_to_rgba "$on_surface")
set notification-error-bg     $(hex_to_rgba "$surface")
set notification-error-fg     $(hex_to_rgba "$error")
set notification-warning-bg   $(hex_to_rgba "$surface")
set notification-warning-fg   $(hex_to_rgba "$warning")

set recolor                   "true"
set recolor-lightcolor        $(hex_to_rgba "$surface")
set recolor-darkcolor         $(hex_to_rgba "$on_surface")

set index-fg                  $(hex_to_rgba "$on_surface")
set index-bg                  $(hex_to_rgba "$surface")
set index-active-fg           $(hex_to_rgba "$on_surface")
set index-active-bg           $(hex_to_rgba "$surface_container")

set render-loading-bg         $(hex_to_rgba "$surface")
set render-loading-fg         $(hex_to_rgba "$on_surface")

set highlight-color           $(hex_to_rgba "$outline" 0.3)
set highlight-fg              $(hex_to_rgba "$on_surface")
set highlight-active-color    $(hex_to_rgba "$primary" 0.3)
EOF
}

