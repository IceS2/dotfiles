# ── Main ──────────────────────────────────────────────────

if [[ "$KITTY_ONLY" == true ]]; then
    generate_kitty
    exit 0
fi

echo "Applying theme from $COLORS_FILE..."

_generate_palette

generate_hyprland
generate_kitty
generate_nvim
generate_starship
generate_hyprlock
generate_zathura
generate_gtk

echo "Theme applied to all consumers."
